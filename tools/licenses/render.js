const crypto = require('node:crypto');

const { normalizeText } = require('./resolve');

const TEXT_KEY_LENGTH = 12;

/**
 * Compares by UTF-16 code units, so the order never depends on the locale of the machine.
 *
 * @param {string} left
 * @param {string} right
 * @returns {number}
 */
function compareCodeUnits(left, right) {
  if (left < right) {
    return -1;
  }
  return left > right ? 1 : 0;
}

/**
 * Stable identifier of a notice: a slug of `name@version` (`heroui-native-1-0-11`).
 *
 * @param {string} name
 * @param {string} version
 * @returns {string}
 */
function noticeId(name, version) {
  return `${name}@${version}`
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

/**
 * Key of a text in `LICENSE_TEXTS`: the first 12 hex digits of its `sha256`.
 *
 * @param {string} text - Normalized text.
 * @returns {string}
 */
function textKeyOf(text) {
  return crypto.createHash('sha256').update(text).digest('hex').slice(0, TEXT_KEY_LENGTH);
}

/**
 * Turns the resolved packages into the data of the generated module, in a stable order, with
 * unique ids and every distinct text stored once.
 *
 * @param {readonly { name: string, version: string, license: string, displayName: string, texts: { spdxId: string, part: 'code' | 'font' | null, text: string }[] }[]} packages
 * @returns {{ notices: object[], texts: Record<string, string> }}
 */
function buildNotices(packages) {
  const sorted = [...packages].sort(
    (left, right) =>
      compareCodeUnits(left.name, right.name) || compareCodeUnits(left.version, right.version),
  );
  const texts = {};
  const ids = new Set();
  const notices = sorted.map((entry) => {
    const id = noticeId(entry.name, entry.version);
    if (ids.has(id)) {
      throw new Error(`Two packages produce the same notice id: ${id}.`);
    }
    ids.add(id);
    return {
      id,
      packageName: entry.name,
      displayName: entry.displayName,
      version: entry.version,
      license: entry.license,
      texts: entry.texts.map(({ spdxId, part, text }) => {
        const normalized = normalizeText(text);
        const textKey = textKeyOf(normalized);
        texts[textKey] = normalized;
        return { spdxId, part, textKey };
      }),
    };
  });
  return { notices, texts: sortedObject(texts) };
}

/**
 * Copy of an object with its keys in code unit order.
 *
 * @param {Record<string, string>} object
 * @returns {Record<string, string>}
 */
function sortedObject(object) {
  return Object.fromEntries(
    Object.entries(object).sort(([left], [right]) => compareCodeUnits(left, right)),
  );
}

/**
 * Source of the generated TypeScript module (before formatting it with Prettier).
 *
 * @param {{ notices: { id: string }[], texts: Record<string, string> }} built
 * @returns {string}
 */
function renderModule({ notices, texts }) {
  const noticeSource = notices
    .map((notice) => {
      const { id, ...rest } = notice;
      return `{ id: ${JSON.stringify(id)} as NoticeId, ${JSON.stringify(rest).slice(1, -1)} }`;
    })
    .join(',\n');
  return `import type { NoticeId, ThirdPartyNotice } from './third-party-notices';

/**
 * One notice per package that the app distributes, ordered by package name and version.
 * Generated by \`npm run licenses:generate\` from the release bundle (ADR-018): do not edit by hand.
 */
export const THIRD_PARTY_NOTICES: readonly ThirdPartyNotice[] = [
${noticeSource}
];

/**
 * License texts without repeats, by \`textKey\`. Generated by \`npm run licenses:generate\`: do not
 * edit by hand.
 */
export const LICENSE_TEXTS: Readonly<Record<string, string>> = ${JSON.stringify(texts)};
`;
}

/**
 * Fingerprint of the production entries of `package-lock.json` (without `dev: true`): changes
 * when a production dependency changes version or integrity.
 *
 * @param {{ packages: Record<string, { version?: string, integrity?: string, dev?: boolean }> }} lock
 * @returns {string} `sha256` in hex.
 */
function lockFingerprint(lock) {
  const lines = Object.entries(lock.packages)
    .filter(([path, entry]) => path !== '' && entry.dev !== true)
    .map(([path, entry]) => `${path}@${entry.version ?? ''}#${entry.integrity ?? ''}`)
    .sort(compareCodeUnits);
  return crypto.createHash('sha256').update(lines.join('\n')).digest('hex');
}

module.exports = { buildNotices, lockFingerprint, renderModule };
